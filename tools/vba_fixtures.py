"""Generate the TEST_Fixtures module of the test build from tests/fixtures and tests/expected.

The VBA tests may not read files (workbook contract W10), so the test build carries the
committed fixtures and expected files as string constants (decision of 2026-10-28, #42).
components.py stage calls generate() with the files of the staged commit; the module is
never committed. Every byte is written as hex, so the module stays ASCII whatever the
fixtures hold.

The data sits in TEST_FixtureData1, TEST_FixtureData2, ... modules of about MODULE_LIMIT
characters each, so that no module approaches the size limits of the VBA editor or of
LibreOffice Basic, used for local smoke runs; TEST_Fixtures holds only the dispatch.

The expected files are flattened to one ``path<TAB>kind<TAB>value`` line per JSON node,
without the provenance: kind is ``o`` (object; value = number of keys, and ``path/~i``
gives the i-th key), ``a`` (array; value = length), ``s`` (string), ``n`` (number),
``b`` (``1`` or ``0``) or ``z`` (null; empty value). Array items and object members are
addressed as ``path/i`` and ``path/key``.
"""
from __future__ import annotations

import json
from typing import Any

NAME = 'TEST_Fixtures'
RESERVED = 'TEST_Fixture'    # every generated module name starts with this; no committed module may
DATA_NAME = 'TEST_FixtureData'
MODULE_LIMIT = 48_000    # characters of data functions per data module, before its header
FIXTURES = 'tests/fixtures/'
EXPECTED = 'tests/expected/'
CHUNK = 200    # hex characters per source line; VBA lines stay far below 1,023 characters


def flatten(node: Any, path: str = '') -> list[tuple[str, str, str]]:
    """The ``(path, kind, value)`` lines of a JSON value."""
    if isinstance(node, dict):
        rows = [(path, 'o', str(len(node)))]
        for i, key in enumerate(node):
            rows.append((f'{path}/~{i}', 's', key))
            rows += flatten(node[key], f'{path}/{key}')
        return rows
    if isinstance(node, list):
        rows = [(path, 'a', str(len(node)))]
        for i, item in enumerate(node):
            rows += flatten(item, f'{path}/{i}')
        return rows
    if isinstance(node, bool):
        return [(path, 'b', '1' if node else '0')]
    if node is None:
        return [(path, 'z', '')]
    if isinstance(node, (int, float)):
        return [(path, 'n', repr(node))]
    return [(path, 's', str(node))]


def expected_text(document: dict[str, Any]) -> bytes:
    data = {k: v for k, v in document.items() if k != 'provenance'}
    lines = [f'{p}\t{k}\t{v}' for p, k, v in flatten(data)]
    for line in lines:
        if '\n' in line or line.count('\t') != 2:
            raise ValueError(f'expected value cannot be flattened: {line!r}')
    return ('\n'.join(lines) + '\n').encode('utf-8')


def vba_string(name: str) -> str:
    if '"' in name or not name.isascii():
        raise ValueError(f'name not usable in VBA source: {name!r}')
    return f'"{name}"'


def data_function(name: str, data: bytes) -> list[str]:
    text = data.hex()
    out = [f'Public Function {name}() As String', '    Dim S As String']
    for i in range(0, len(text), CHUNK):
        out.append(f'    S = S & "{text[i:i + CHUNK]}"')
    out += [f'    {name} = S', 'End Function', '']
    return out


def header(name: str, commit: str, lines: list[str]) -> list[str]:
    return [
        f'Attribute VB_Name = "{name}"',
        "'" + '=' * 78,
        f"' MODULE: {name}",
        "'" + '-' * 78,
        "' GENERATED by tools/vba_fixtures.py from tests/fixtures and tests/expected",
        f"' at commit {commit}.",
        "' Never edit or commit it; components.py stage writes it into the test",
        "' build only.",
        *lines,
        "'" + '=' * 78,
        '',
        'Option Explicit',
        'Option Private Module',
        '',
    ]


def generate(files: dict[str, bytes], commit: str) -> dict[str, str]:
    """{module name: text} from {repository path: bytes} of tests/fixtures/** and tests/expected/*.json."""
    fixtures = {p[len(FIXTURES):]: b for p, b in sorted(files.items()) if p.startswith(FIXTURES)}
    expected = {p[len(EXPECTED):-5]: expected_text(json.loads(b))
                for p, b in sorted(files.items()) if p.startswith(EXPECTED) and p.endswith('.json')}
    # Data functions, packed into data modules in order.
    modules: list[list[str]] = [[]]
    sizes = [0]
    where: dict[str, str] = {}
    for prefix, table in (('F', fixtures), ('X', expected)):
        for i, data in enumerate(table.values()):
            name = f'{prefix}{i:04d}'
            code = data_function(name, data)
            size = sum(len(line) + 1 for line in code)
            if sizes[-1] and sizes[-1] + size > MODULE_LIMIT:
                modules.append([])
                sizes.append(0)
            modules[-1] += code
            sizes[-1] += size
            where[name] = f'{DATA_NAME}{len(modules)}'
    out = header(NAME, commit, [
        "'",
        "' TEST_FixtureBytes(Path, Length)  the bytes of tests/fixtures/<Path>",
        "' TEST_ExpectedBytes(CaseId, Length)  the flattened tests/expected/<CaseId>.json",
        "' TEST_HasFixture(Path)            True when tests/fixtures/<Path> exists",
        "'   Both return a 0-based Byte array in a Variant and set Length; an empty",
        f"'   file returns one unused byte and Length 0. The data is in {DATA_NAME}1 to",
        f"'   {DATA_NAME}{len(modules)}.",
    ])
    for public, table, prefix in (('TEST_FixtureBytes(ByVal Path As String', fixtures, 'F'),
                                  ('TEST_ExpectedBytes(ByVal CaseId As String', expected, 'X')):
        key = 'Path' if prefix == 'F' else 'CaseId'
        name = public.split('(')[0]
        out += [f'Public Function {public}, ByRef Length As Long) As Variant', f'    Select Case {key}']
        for i, item in enumerate(table):
            function = f'{prefix}{i:04d}'
            out.append(f'        Case {vba_string(item)}: {name} = Decode({where[function]}.{function}(), Length)')
        out += [f'        Case Else: Err.Raise vbObjectError + 1, "{NAME}", "Not in the test build: " & {key}',
                '    End Select', 'End Function', '']
    out += ['Public Function TEST_HasFixture(ByVal Path As String) As Boolean', '    Select Case Path']
    out += [f'        Case {vba_string(item)}: TEST_HasFixture = True' for item in fixtures]
    out += ['    End Select', 'End Function', '']
    out += [
        'Private Function Decode(ByVal HexText As String, ByRef Length As Long) As Variant',
        '    Dim B() As Byte, I As Long',
        '    Length = Len(HexText) \\ 2',
        '    If Length = 0 Then',
        '        ReDim B(0 To 0)',
        '    Else',
        '        ReDim B(0 To Length - 1)',
        '    End If',
        '    For I = 0 To Length - 1',
        '        B(I) = HexDigit(Mid$(HexText, 2 * I + 1, 1)) * 16 + HexDigit(Mid$(HexText, 2 * I + 2, 1))',
        '    Next I',
        '    Decode = B',
        'End Function',
        '',
        'Private Function HexDigit(ByVal Ch As String) As Long',
        '    HexDigit = InStr(1, "0123456789abcdef", Ch, vbBinaryCompare) - 1',
        'End Function',
        '',
    ]
    result = {NAME: out}
    for n, code in enumerate(modules, start=1):
        result[f'{DATA_NAME}{n}'] = header(f'{DATA_NAME}{n}', commit, [
            "'", f"' Data functions behind {NAME}: the hex text of one fixture or expected file each."]) + code
    texts = {name: '\n'.join(lines).rstrip('\n') + '\n' for name, lines in result.items()}
    assert all(t.isascii() for t in texts.values())
    return texts
